const byCode = new Map(REGIONS.map((r) => [r.code, r]));

export function regionByCode(code: number | null | undefined): Region | null {
  return code ? (byCode.get(code) ?? null) : null;
}

/** Ключ для сравнения названий: без регистра, скобок, «г.», тире и ё. */
export function regionKey(s: string): string {
  return s
    .toUpperCase()
    .replace(/Ё/g, "Е")
    .replace(/\(.*?\)/g, " ")
    .replace(/^\s*Г(ОРОД)?\.?\s+/, "")
    .replace(/[—–-]/g, " ")
    .replace(/[^А-ЯA-Z0-9 ]/g, " ")
    .replace(/ АО$/, " АВТОНОМНЫЙ ОКРУГ")
    .replace(/\s+/g, " ")
    .trim();
}

const byKey = new Map<string, Region>();
for (const r of REGIONS) {
  byKey.set(regionKey(r.name), r);
}
