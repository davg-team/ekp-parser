/** Находит субъект по произвольному написанию. */
export function findRegion(text: string | null | undefined): Region | null {
  if (!text) return null;
  const key = regionKey(text);
  if (!key) return null;
  const exact = byKey.get(key);
  if (exact) return exact;
  // «РЕСПУБЛИКА ТАТАРСТАН ТАТАРСТАН», «Г САНКТ ПЕТЕРБУРГ» и т.п. — ищем самое длинное совпадение-префикс.
  let best: Region | null = null;
  let bestLen = 0;
  for (const [k, r] of byKey) {
    if (k.length > bestLen && (key === k || key.startsWith(k + " ") || key.includes(" " + k + " ") || key.endsWith(" " + k))) {
      best = r;
      bestLen = k.length;
    }
  }
  return best;
}
